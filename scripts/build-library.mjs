// ---------------------------------------------------------------- pieces

function svgFor(p, lang, { decorative = false } = {}) {
  const t = p[lang];
  const filled = p.svg.replace(/\{\{(\w+)\}\}/g, (_, key) => esc(t.svg_labels[key]));
  const attrs = decorative ? ` aria-hidden="true" focusable="false"` : ` role="img" aria-label="${esc(t.svg_alt)}"`;
  return filled.replace(/^<svg/, `<svg class="pattern-svg"${attrs}`);
}

function tags(p, lang) {
  const w = WORDS[lang], c = categoryOf(p);
  // Neutral patterns either show indecision (doji) or work in both directions (pin bar, symmetrical triangle).
  const kind = p.pattern_type === "indecision" ? w.indecision : w.type[`${p.direction}:${p.pattern_type}`] || w.direction[p.direction];
  const arrow = p.direction === "bullish" ? "↑ " : p.direction === "bearish" ? "↓ " : "";
  return `<ul class="tags"><li class="tag tag-cat">${esc(c[lang].singular)}</li><li class="tag tag-${esc(p.direction)}">${arrow}${esc(kind)}</li><li class="tag">${esc(w.candles[String(p.candles)])}</li></ul>`;
}

function card(p, lang) {
  const t = p[lang];
  const search = [t.name, t.alt_name].filter(Boolean).join(" ").toLocaleLowerCase(lang);
  return `<li class="pattern-card" data-kind="${esc(p.kind)}" data-direction="${esc(p.direction)}" data-search="${esc(search)}"><a href="${esc(urls.pattern(p, lang))}"><div class="card-svg">${svgFor(p, lang, { decorative: true })}</div><h3>${esc(t.name)}</h3>${t.alt_name ? `<p class="alt">${esc(t.alt_name)}</p>` : ""}${tags(p, lang)}<p>${esc(firstSentence(t.summary))}</p></a></li>`;
}

const breadcrumb = (lang, items) => `<nav class="crumbs" aria-label="Breadcrumb"><ol>${items.map(([label, href]) => `<li>${href ? `<a href="${esc(href)}">${esc(label)}</a>` : `<span aria-current="page">${esc(label)}</span>`}</li>`).join("")}</ol></nav>`;

