// ---------------------------------------------------------------- helpers

const esc = (value) => String(value ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
// The only markup allowed in content: **bold**. Everything else is escaped.
const inline = (text) => esc(String(text ?? "").trim()).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
const plain = (text) => String(text ?? "").replace(/\*\*/g, "").replace(/\s+/g, " ").trim();
const firstSentence = (text) => { const t = plain(text); const m = t.match(/^.+?[.!?](?=\s|$)/); return m ? m[0] : t; };
const isText = (v) => typeof v === "string" && v.trim() !== "";
const isTextList = (v) => Array.isArray(v) && v.length > 0 && v.every(isText);
const assetHash = (file) => createHash("sha1").update(readFileSync(join(ROOT, file))).digest("hex").slice(0, 8);
const asset = (file) => `/${file}?v=${assetHash(file)}`;
const readYaml = (file) => {
  try { return parse(readFileSync(file, "utf8")); } catch (e) { fail(relative(ROOT, file), `invalid YAML: ${e.message}`); return null; }
};

