// The sitemap lists the site's indexable pages; library pages carry their last update.
const lastmod = (list) => list.map((p) => p.updated).sort().pop();
const entry = (path, mod) => `  <url><loc>${ORIGIN}${path}</loc>${mod ? `<lastmod>${mod}</lastmod>` : ""}</url>`;
const sitemap = [
  `<?xml version="1.0" encoding="UTF-8"?>`,
  `<!-- Generated by scripts/build-library.mjs. Do not edit by hand. -->`,
  `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">`,
  entry("/"), entry("/weekly-events"),
  ...LANGS.flatMap((lang) => [
    entry(urls.home(lang), lastmod(patterns)),
    ...categories.map((c) => entry(urls.category(c, lang), lastmod(patterns.filter((p) => p.kind === c.kind)))),
    ...sorted(patterns).map((p) => entry(urls.pattern(p, lang), p.updated)),
  ]),
  `</urlset>`, "",
].join("\n");
files.set(join(ROOT, "sitemap.xml"), sitemap);

// Every library page lives under these folders, so a renamed or removed page is cleaned up too.
const OWNED = LANGS.map((lang) => join(ROOT, BASE[lang]));
const existing = [];
const walk = (dir) => { if (!existsSync(dir)) return; for (const e of readdirSync(dir, { withFileTypes: true })) { const p = join(dir, e.name); if (e.isDirectory()) walk(p); else existing.push(p); } };
OWNED.forEach(walk);

for (const w of warnings) console.warn(`warning: ${w}`);

if (CHECK) {
  const stale = [...files].filter(([file, html]) => !existsSync(file) || readFileSync(file, "utf8") !== html).map(([file]) => relative(ROOT, file));
  const extra = existing.filter((file) => !files.has(file)).map((file) => relative(ROOT, file));
  if (stale.length || extra.length) {
    console.error(`The library pages are out of date. Run "node scripts/build-library.mjs" and commit the result.\n  ${[...stale.map((f) => `changed: ${f}`), ...extra.map((f) => `not generated: ${f}`)].join("\n  ")}`);
    process.exit(1);
  }
  console.log(`Library pages are up to date (${patterns.length} patterns, ${files.size} files).`);
} else {
  OWNED.forEach((dir) => rmSync(dir, { recursive: true, force: true }));
  for (const [file, html] of files) { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, html); }
  console.log(`Built ${files.size} files from ${patterns.length} patterns.`);
}
